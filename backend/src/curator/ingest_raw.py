def _clean_section_title(title: str, fallback: str) -> str:
    title = re.sub(r"\s+", " ", title or "").strip()
    return title[:120] or fallback


_LOCAL_HEADING_WIKILINK_RE = re.compile(
    r"\[\[([^/\]|#\n]+)#([^\]|#\n]+)(?:\|([^\]\n]+))?\]\]"
)


def _plain_local_heading_wikilinks(text: str) -> str:
    """Plaintext parser-generated same-document heading wikilinks in CTX output."""
    if not text:
        return ""

    def _replace(match: re.Match) -> str:
        alias = (match.group(3) or "").strip()
        heading = (match.group(2) or "").strip()
        return alias or heading

    return _LOCAL_HEADING_WIKILINK_RE.sub(_replace, text)


def _extract_markdown_sections(text: str, *, default_title: str) -> list[dict]:
    """Split text into structural sections without using an LLM."""
    matches = list(re.finditer(r"(?m)^(#{1,6})\s+(.+?)\s*$", text or ""))
    if not matches:
        return [
            {
                "id": _section_id(1),
                "level": 2,
                "title": _clean_section_title(default_title, "Document"),
                "page": 1,
                "text": (text or "").strip(),
            }
        ]

    sections: list[dict] = []
    for idx, match in enumerate(matches, 1):
        next_start = matches[idx].start() if idx < len(matches) else len(text)
        heading = _clean_section_title(match.group(2), f"Section {idx}")
        body = text[match.end() : next_start].strip()
        sections.append(
            {
                "id": _section_id(idx),
                "level": min(len(match.group(1)), 6),
                "title": heading,
                "page": 1,
                "text": body,
            }
        )
    return sections


# Patterns that identify heading-like lines in raw PDF text
_NUMBERED_HEADING = re.compile(
    r"^(\d+\.)+\s+[A-Z]",          # "1. Introduction", "2.1 Methods"
)
_ALLCAPS_HEADING = re.compile(
    r"^[A-Z][A-Z\s\-/]{2,49}$",    # "INTRODUCTION", "METHODS AND RESULTS"
)
_KNOWN_SECTION_NAMES = frozenset({
    "abstract", "introduction", "background", "related work",
    "motivation", "methodology", "methods", "method", "approach",
    "experiment", "experiments", "evaluation", "results",
    "discussion", "conclusion", "conclusions", "future work",
    "acknowledgment", "acknowledgments", "acknowledgements",
    "references", "bibliography", "appendix",
})


def _looks_like_heading(line: str) -> tuple[bool, int]:
    """Return (is_heading, level). Level 1 for top-level, 2 for sub."""
    stripped = line.strip()
    if not stripped or len(stripped) > 80:
        return False, 0
    if _NUMBERED_HEADING.match(stripped):
        depth = stripped.split()[0].count(".")
        return True, max(1, depth)
    if _ALLCAPS_HEADING.match(stripped) and not stripped[0].isdigit():
        return True, 1
    lower = stripped.lower().rstrip(".:")
    if lower in _KNOWN_SECTION_NAMES and len(stripped) <= 40:
        return True, 1
    return False, 0


def _infer_sections_from_layout(pages: list[dict]) -> list[dict]:
    """Detect heading-like lines across page text and group content into sections.

    Returns [] if fewer than 2 headings are found (caller falls back to page-by-page).
    """
    # Collect (page_no, line_idx, heading_text, level) for each detected heading
    heading_anchors: list[tuple[int, int, str, int]] = []
    for page in pages:
        page_no = int(page.get("page") or page.get("page_number") or 0)
        if not page_no:
            continue
        text = str(page.get("text") or "")
        lines = text.splitlines()
        for li, line in enumerate(lines):
            is_h, level = _looks_like_heading(line)
            if is_h:
                heading_anchors.append((page_no, li, line.strip(), level))

    if len(heading_anchors) < 2:
        return []

    # Build sections: each heading spans from its page to the next heading's page
    page_text_by_no = {
        int(p.get("page") or p.get("page_number") or 0): str(p.get("text") or "").strip()
        for p in pages
        if int(p.get("page") or p.get("page_number") or 0) > 0
    }
    sorted_page_nos = sorted(page_text_by_no)

    sections: list[dict] = []
    for anchor_idx, (start_page, _li, heading, level) in enumerate(heading_anchors):
        next_start = heading_anchors[anchor_idx + 1][0] if anchor_idx + 1 < len(heading_anchors) else None
        section_pages = [
            pn for pn in sorted_page_nos
            if pn >= start_page and (next_start is None or pn < next_start)
        ]
        text = "\n\n".join(page_text_by_no[pn] for pn in section_pages).strip()
        sections.append({
            "id": _section_id(len(sections) + 1),
            "level": level,
            "title": _clean_section_title(heading, f"Section {len(sections) + 1}"),
            "page": start_page,
            "text": text,
        })

    return sections


def _extract_pdf_sections(parsed) -> list[dict]:
    pages = parsed.metadata.get("pdf_pages") or []
    toc = parsed.metadata.get("pdf_toc") or []
    if isinstance(pages, list) and isinstance(toc, list) and toc:
        page_text_by_number = {
            int(p.get("page") or p.get("page_number") or 0): str(p.get("text") or "").strip()
            for p in pages
            if int(p.get("page") or p.get("page_number") or 0) > 0
        }
        sorted_pages = sorted(page_text_by_number)
        sections: list[dict] = []
        for idx, item in enumerate(toc, 1):
            try:
                level = int(item.get("level") or 1)
                start_page = int(item.get("page") or 1)
            except (AttributeError, TypeError, ValueError):
                continue
            next_page = None
            for next_item in toc[idx:]:
                try:
                    candidate_page = int(next_item.get("page") or 0)
                except (AttributeError, TypeError, ValueError):
                    continue
                if candidate_page > start_page:
                    next_page = candidate_page
                    break
            section_pages = [
                page_no
                for page_no in sorted_pages
                if page_no >= start_page and (next_page is None or page_no < next_page)
            ]
            text = "\n\n".join(page_text_by_number[p] for p in section_pages).strip()
            sections.append(
                {
                    "id": _section_id(len(sections) + 1),
                    "level": max(1, min(level, 6)),
                    "title": _clean_section_title(str(item.get("title") or ""), f"Section {idx}"),
                    "page": start_page,
                    "text": text,
                }
            )
        if sections:
            return sections

    if isinstance(pages, list) and pages:
        # Try to infer logical sections from text layout before falling back to page-by-page.
        inferred = _infer_sections_from_layout(pages)
        if inferred:
            return inferred

        # Page-by-page fallback when no layout headings detected
        sections = []
        for page in pages:
            page_no = int(page.get("page") or page.get("page_number") or len(sections) + 1)
            text = str(page.get("text") or "").strip()
            if not text:
                continue
            sections.append(
                {
                    "id": _section_id(len(sections) + 1),
                    "level": 2,
                    "title": f"Page {page_no}",
                    "page": page_no,
                    "text": text,
                }
            )
        if sections:
            return sections

    return _extract_markdown_sections(parsed.text, default_title=parsed.title)


def _extract_structural_sections(parsed) -> list[dict]:
    if parsed.file_type == "pdf":
        return _extract_pdf_sections(parsed)
    return _extract_markdown_sections(parsed.text, default_title=parsed.title)


def _structural_atom_candidates(sections: list[dict], title: str) -> list[dict]:
    candidates: list[dict] = []
    for section in sections[:24]:
        section_title = _plain_local_heading_wikilinks(
            _clean_section_title(str(section.get("title") or ""), title)
        )
        page = int(section.get("page") or 1)
        preview = _section_preview(_plain_local_heading_wikilinks(str(section.get("text") or "")))
        candidates.append(
            {
                "name": section_title,
                "type": consts.CLAIM_TYPE_FACT,
                "one_liner": (
                    "Extract the atomic claims, methods, entities, equations, and constraints "
                    f"from section '{section_title}' starting on page {page}."
                    + (f" Preview: {preview}" if preview else "")
                ),
            }
        )
    if candidates:
        return candidates
    return [
        {
            "name": _plain_local_heading_wikilinks(_clean_section_title(title, "Document")),
            "type": consts.CLAIM_TYPE_FACT,
            "one_liner": "Extract the atomic claims, methods, entities, and constraints from this source.",
        }
    ]


def _section_preview(text: str, *, max_chars: int = 260) -> str:
    """Return a compact source-text preview without destroying math/code recall."""
    cleaned = re.sub(r"(?s)```.*?```", " ", text)
    cleaned = re.sub(r"(?s)\$\$.*?\$\$", " ", cleaned)
    cleaned = re.sub(
        r"(?is)\*\*----- Start of picture text -----\*\*<br>.*?\*\*----- End of picture text -----\*\*<br>",
        " ",
        cleaned,
    )
    cleaned = re.sub(r"!\[\[.*?\]\]", " ", cleaned)
    cleaned = re.sub(r"\*\*==>.*?intentionally omitted.*?<==\*\*", " ", cleaned)
    cleaned = re.sub(r"\s+", " ", cleaned).strip()
    if not cleaned:
        return ""
    if len(cleaned) <= max_chars:
        return cleaned

    # Prefer sentence boundaries when available; otherwise fall back to a word
    # boundary slice. This text is a retrieval hint, not a lossy replacement for
    # Source Sections.
    boundary = re.search(r"(?<=[.!?])\s+", cleaned[: max_chars + 80])
    if boundary and boundary.end() > 40:
        preview = cleaned[: boundary.start() + 1]
    else:
        preview = cleaned[:max_chars].rsplit(" ", 1)[0] or cleaned[:max_chars]
    return preview.rstrip(" ,;:") + ("..." if len(cleaned) > len(preview) else "")


L1_INLINE_SOURCE_MAX_CHARS = 200_000
L1_INLINE_SOURCE_MAX_PAGES = 200


def _source_page_count(parsed, sections: list[dict]) -> int:
    page_count = parsed.metadata.get("page_count") or parsed.metadata.get("pdf_page_count")
    if not page_count:
        pages = [int(section.get("page") or 1) for section in sections]
        page_count = max(pages) if pages else 1
    return int(page_count or 1)


def _should_inline_source_sections(parsed, sections: list[dict]) -> bool:
    """Return whether L1 should inline full raw text instead of a compact minimap."""
    total_chars = sum(len(str(section.get("text") or "")) for section in sections)
    page_count = _source_page_count(parsed, sections)
    return total_chars <= L1_INLINE_SOURCE_MAX_CHARS and page_count <= L1_INLINE_SOURCE_MAX_PAGES


def _build_structural_source_guide(
    parsed,
    sections: list[dict],
    *,
    inline_source_sections: bool,
) -> tuple[str, str, str]:
    """Build English L1 retrieval scaffolding while preserving source recall."""
    section_count = len(sections)
    page_count = _source_page_count(parsed, sections)
    source_policy = (
        "the full original source text is preserved in `Source Sections`"
        if inline_source_sections
        else "large-document raw text is kept in the original source and fetched on demand"
    )
    display_title = _plain_local_heading_wikilinks(str(parsed.title or "Untitled"))

    summary = (
        f"Structural L1 context for **{display_title}**. "
        f"The parser found {section_count} source section(s)"
        f" across {page_count} page(s). "
        f"Use the section ids and page numbers below for recall; {source_policy} "
        "for exact lookup, math, tables, and later extraction."
    )

    guide_lines = [
        "- Generated scaffold language: English.",
        (
            "- Source truth: original text under `Source Sections`; do not treat the previews as a replacement for raw evidence."
            if inline_source_sections
            else "- Source truth: original file text; use `fetch_document_section` with `toc_id` or page ranges for raw evidence."
        ),
        "- Provenance shape: each preview maps to `section_id`, `page`, and the matching HTML section marker.",
        "",
        "### Section Previews",
    ]
    claim_lines: list[str] = []
    for idx, section in enumerate(sections[:24], 1):
        sid = str(section.get("id") or _section_id(idx))
        title = _plain_local_heading_wikilinks(
            _clean_section_title(str(section.get("title") or ""), f"Section {idx}")
        )
        page = int(section.get("page") or 1)
        preview = _section_preview(_plain_local_heading_wikilinks(str(section.get("text") or "")))
        if preview:
            guide_lines.append(f"- `{sid}` p.{page} — **{title}**: {preview}")
            claim_lines.append(
                f"- `{sid}` p.{page} **{title}**: {preview}"
            )
        else:
            guide_lines.append(f"- `{sid}` p.{page} — **{title}**: no text preview available.")
            claim_lines.append(
                f"- `{sid}` p.{page} **{title}**: source section is available for extraction."
            )

    return summary, "\n".join(claim_lines), "\n".join(guide_lines)


def _safe_vault_subdir(paths: cfg.WikiPaths, candidate: str) -> str | None:
    """Validate a vault-relative folder for asset writes.

    Returns the normalized POSIX-style relative path, or None when the value is
    empty, absolute, or escapes the vault root (e.g. via `..`). Routing must
    never write outside the vault.
    """
    try:
        candidate = (candidate or "").strip()
        if not candidate:
            return None
        if Path(candidate).is_absolute():
            return None
        root = paths.root.resolve()
        resolved = (root / candidate).resolve()
        if resolved == root or not resolved.is_relative_to(root):
            return None
        return resolved.relative_to(root).as_posix()
    except Exception:
        return None


def _save_pdf_images(
    parsed, relpath: str, paths: cfg.WikiPaths, asset_dir: str | None = None
) -> list[dict]:
    """Save embedded PDF images and return obsidian metadata.

    Images land in `asset_dir` (vault-relative, validated by
    `_safe_vault_subdir`) when provided and safe, otherwise in the legacy
    `05_Assets/<slug>/`. The returned `obsidian_path` always matches the folder
    actually written so `![[...]]` embeds resolve in both cases.
    Images smaller than 1 KB are skipped (icons, decorators).
    Returns [] when parsed is not a PDF or has no images. Silently ignores errors.
    """
    if parsed.file_type != "pdf":
        return []
    pdf_images: list[dict] = parsed.metadata.get("pdf_images", [])
    if not pdf_images:
        return []

    obsidian_prefix = _safe_vault_subdir(paths, asset_dir) if asset_dir else None
    if not obsidian_prefix:
        slug = re.sub(r"[^\w\-]", "_", Path(relpath).stem)[:40].strip("_") or "source"
        obsidian_prefix = f"{consts.DIR_ASSETS}/{slug}"
    assets_dir = paths.root / obsidian_prefix
    saved: list[dict] = []
    try:
        assets_dir.mkdir(parents=True, exist_ok=True)
        idx_per_page: dict[int, int] = {}
        for img in pdf_images:
            page = int(img.get("page", 1))
            idx_per_page[page] = idx_per_page.get(page, 0) + 1
            idx = idx_per_page[page]
            ext = str(img.get("ext", "png"))
            filename = f"p{page:02d}_img{idx:02d}.{ext}"
            dest = assets_dir / filename
            dest.write_bytes(img["data"])
            saved.append({"obsidian_path": f"{obsidian_prefix}/{filename}", "page": page})
    except Exception:
        pass
    return saved


def _build_structural_context_page(
    *,
    context_id: str,
    parsed,
    relpath: str,
    content_hash: str,
    today: str,
    saved_images: list[dict] | None = None,
) -> str:
    import yaml

    sections = _extract_structural_sections(parsed)
    candidates = _structural_atom_candidates(sections, parsed.title)
    compact_pages: list[dict] = []
    pdf_pages = parsed.metadata.get("pdf_pages") or []
    if parsed.file_type == "pdf" and isinstance(pdf_pages, list):
        compact_pages = [
            {
                "page": int(p.get("page") or 0),
                "hash": str(p.get("content_hash") or "")[:16],
                "chars": int(p.get("char_count") or 0),
                "words": int(p.get("word_count") or 0),
            }
            for p in pdf_pages
            if int(p.get("page") or 0) > 0
        ]

    frontmatter: dict = {
        "id": context_id,
        "type": consts.TYPE_L1,
        "source_path": f"[[{relpath.removesuffix('.md')}]]",
        "source_hash": content_hash,
        "content_hash": hashlib.sha256((parsed.text or "").encode("utf-8")).hexdigest()[:16],
        "domain": consts.DOMAIN_GENERAL,
        "last_updated": today,
        "tags": [parsed.file_type, "instant-l1"],
        "toc": [
            {
                "id": str(section.get("id") or _section_id(idx)),
                "level": int(section.get("level") or 2),
                "title": _plain_local_heading_wikilinks(str(section.get("title") or f"Section {idx}")),
                "page": int(section.get("page") or 1),
            }
            for idx, section in enumerate(sections, 1)
        ],
    }
    if compact_pages:
        frontmatter["source_page_count"] = len(compact_pages)
        frontmatter["source_pages"] = compact_pages
    if saved_images:
        frontmatter["embedded_images"] = [
            {"obsidian_path": img["obsidian_path"], "page": img["page"]}
            for img in saved_images
        ]

    inline_source_sections = _should_inline_source_sections(parsed, sections)
    source_char_count = sum(len(str(section.get("text") or "")) for section in sections)
    frontmatter["source_sections_inline"] = inline_source_sections
    frontmatter["source_text_policy"] = "inline" if inline_source_sections else "on_demand"
    frontmatter["source_char_count"] = source_char_count

    summary_text, key_claims_text, source_guide_text = _build_structural_source_guide(
        parsed,
        sections,
        inline_source_sections=inline_source_sections,
    )
    candidates_text = "\n".join(
        f"- [{candidate['type']}] {candidate['name']}: {candidate['one_liner']}"
        for candidate in candidates
    )
    page_provenance = ""
    if compact_pages:
        page_provenance = (
            "\n\n## Source Page Provenance\n\n"
            + "\n".join(
                f"- p. {p['page']}: {p['words']} words, hash `{p['hash']}`"
                for p in compact_pages
            )
            + "\n"
        )

    source_sections = []
    for idx, section in enumerate(sections, 1):
        level = max(2, min(int(section.get("level") or 2), 6))
        sid = str(section.get("id") or _section_id(idx))
        page_num = int(section.get("page") or 1)
        title = _plain_local_heading_wikilinks(str(section.get("title") or f"Section {idx}"))
        body = _plain_local_heading_wikilinks(str(section.get("text") or "")).strip()
        if not inline_source_sections:
            preview = _section_preview(body, max_chars=420)
            body = (
                f"Raw source text is not duplicated in this L1 page because the source is large. "
                f"Fetch exact evidence on demand with `fetch_document_section(source_key=\"{relpath}\", toc_id=\"{sid}\")`"
                f" or page `{page_num}`."
                + (f"\n\nPreview: {preview}" if preview else "")
            )
        source_sections.append(
            "\n".join(
                [
                    f"<!-- section:{sid} page:{page_num} -->",
                    f"{'#' * level} {title}",
                    "",
                    body,
                ]
            ).strip()
        )

    fm = yaml.safe_dump(
        frontmatter,
        sort_keys=False,
        default_flow_style=False,
        allow_unicode=True,
    ).strip()
    source_sections_text = "\n\n".join(source_sections)
    figures_section = ""
    if saved_images:
        figures_section = "\n\n## Embedded Figures\n\n" + "\n\n".join(
            f"![[{img['obsidian_path']}]]\n*Figure (p.{img['page']})*"
            for img in saved_images
        )
    return (
        f"---\n{fm}\n---\n\n"
        "## Summary\n\n"
        f"{summary_text}\n\n"
        "## 1. Key Claims\n\n"
        f"{key_claims_text}\n"
        f"{page_provenance}"
        "\n## Source Guide\n\n"
        f"{source_guide_text}\n\n"
        "\n## 2. Atom Candidates\n\n"
        f"{candidates_text}\n\n"
        "## Source Sections\n\n"
        f"{source_sections_text}"
        f"{figures_section}\n"
    )


def generate_l1_structural_context(
    paths: cfg.WikiPaths,
    source_id: int,
    relpath: str,
    content_hash: str,
    *,
    existing_context_id: str | None = None,
    asset_dir: str | None = None,
) -> str | None:
    """Create an L1 Context from parser structure only."""
    file_path = paths.root / relpath
    if not file_path.exists():
        print(f"  [Error] File does not exist at: {file_path}")
        return None

    try:
        resolved_source = _resolve_reference_source(paths, file_path)
        parsed = parsers.parse(resolved_source)
        # v0.22.0: user-elected vision_model transcribes PDF pages to LaTeX L1
        # (SYSTEM_BEHAVIOR §26.2a). Only for PDFs; only when vision_model is set.
        # A configured-but-bad vision model raises here (R13) → l1 error below.
        if parsed.file_type == "pdf":
            _vcfg = cfg.load_config(paths)
            _vclient = _resolve_vision_client(_vcfg, None)
            if _vclient is not None:
                _apply_vlm_pdf_extraction(
                    parsed, resolved_source, _vclient, _vcfg, paths.state_db
                )
    except Exception as e:
        print(f"  [Error] Parsing file failed for {relpath}: {e}")
        db.set_source_layer_status(paths.state_db, source_id, "l1", "error", error=str(e))
        return None

    context_id = existing_context_id or _generate_id(consts.PREFIX_L1)
    saved_images = _save_pdf_images(parsed, relpath, paths, asset_dir=asset_dir)
    page_content = _build_structural_context_page(
        context_id=context_id,
        parsed=parsed,
        relpath=relpath,
        content_hash=content_hash,
        today=_now_iso(),
        saved_images=saved_images or None,
    )

    paths.contexts.mkdir(parents=True, exist_ok=True)
    context_path = paths.contexts / f"{context_id}.md"
    operation = "updated" if context_path.exists() else "created"
    context_path.write_text(page_content, encoding="utf-8")

    with db.connect(paths.state_db) as conn:
        conn.execute(
            "UPDATE sources SET context_id = ? WHERE id = ?",
            (context_id, source_id),
        )
        conn.execute(
            "UPDATE sources SET l1_status = 'done', layer_error = NULL WHERE id = ?",
            (source_id,),
        )

    _record_pdf_pages_for_parsed(paths, source_id, relpath, parsed)

    # v0.3.1: deterministically extract source_spans into the DB (no LLM). The
    # DB is the source of truth; the CTX page above is the derived projection.
    try:
        from .pipeline import source_spans as _source_spans

        sections = _extract_structural_sections(parsed)
        spans = _source_spans.spans_from_sections(sections)
        _source_spans.store_source_spans(paths.state_db, source_id, relpath, spans)
    except Exception as e:  # span extraction must never break instant L1
        print(f"  [Warn] source span extraction failed for {relpath}: {e}")

    db.record_source_page(
        paths.state_db,
        source_id,
        f"{consts.LAYER_L1}/{context_id}.md",
        operation,
    )
    return context_id


def _require_vision(client, slot: str):
    """Return a vision-capable client for a CONFIGURED slot, else RAISE (v0.22.0).

    A configured-but-bad model never silently falls through to a heavier model
    (SYSTEM_BEHAVIOR §26.2a, R13) — that would spike latency/cost and hide broken
    config. Only an EMPTY slot is allowed to fall through (handled by the callers).
    """
    if client is None:
        raise LLMError(f"llm.{slot} is set but its provider/model could not be built")
    if not getattr(client, "supports_vision", False):
        model = getattr(client, "model", "?")
        raise LLMError(
            f"llm.{slot} model '{model}' is not vision-capable; choose a vision model "
            f"or clear the slot"
        )
    return client


def _resolve_vision_client(config: dict, main_client):
    """Heavy ingest/image vision model: ``vision_model`` → main-if-vision → None.

    Used by `add source` PDF ingest and standalone/markdown image description. NEVER
    consults ``latex_extract_model`` (R10). Empty → fall through; configured-bad → raise.
    """
    from . import llm

    vm = (config.get("llm", {}).get("vision_model") or "").strip()
    if vm:
        return _require_vision(llm.make_client_for(vm, config), "vision_model")
    if getattr(main_client, "supports_vision", False):
        return main_client
    return None


def _resolve_extract_client(config: dict, main_client):
    """Light interactive region model: ``latex_extract_model`` → vision chain.

    Empty → fall through to the vision chain; configured-bad → raise. (Provided for
    completeness / future server-side region tasks; ingest does NOT use this.)
    """
    from . import llm

    lm = (config.get("llm", {}).get("latex_extract_model") or "").strip()
    if lm:
        return _require_vision(llm.make_client_for(lm, config), "latex_extract_model")
    return _resolve_vision_client(config, main_client)


# Backwards-compatible alias: ingest image-description path resolves the heavy model.
def _build_vision_client(config: dict, main_client):
    return _resolve_vision_client(config, main_client)


def _apply_vlm_pdf_extraction(parsed, file_path, vision_client, config, db_path) -> None:
    """Replace L1 page text with vision-model transcription (SYSTEM_BEHAVIOR §26.2a).

    Mutates ``parsed`` in place: per page keep the pymupdf4llm text as ``parser_text``,
    set ``text`` to the VLM transcription (cache-keyed by rendered-image hash + model,
    per-page fallback to ``parser_text`` on failure), rebuild ``parsed.text``, and set
    ``parser_used="vlm"``. Enforces the ``vision_max_pages_per_run`` rail.
    """
    from concurrent.futures import ThreadPoolExecutor

    from . import vision

    llm_cfg = config.get("llm", {})
    dpi = int(llm_cfg.get("vision_render_dpi", 170))
    max_px = int(llm_cfg.get("vision_max_image_px", 1600))
    max_pages = int(llm_cfg.get("vision_max_pages_per_run", 300))
    model = getattr(vision_client, "model", "?") or "?"

    pdf_pages = parsed.metadata.get("pdf_pages") or []
    if not pdf_pages:
        return
    images = vision.render_pdf_pages(file_path, dpi=dpi, max_px=max_px)
    n = min(len(images), len(pdf_pages))
    transcribe_n = min(n, max_pages)
    skipped = n - transcribe_n
    if skipped > 0:
        print(
            f"  [Info] vision: transcribing {transcribe_n}/{n} pages; {skipped} "
            f"skipped (vision_max_pages_per_run={max_pages}, vision_skipped) — those "
            f"pages keep pymupdf4llm text."
        )

    # SQLite has no concurrent writers, so keep all DB access on the main thread:
    # (1) serial cache lookup, (2) concurrent transcription of misses with NO DB
    # access in worker threads, (3) serial cache write.
    hashes = [hashlib.sha256(images[i]).hexdigest()[:16] for i in range(transcribe_n)]
    results: dict[int, str | None] = {}
    misses: list[int] = []
    for i in range(transcribe_n):
        cached = db.vision_cache_get(db_path, hashes[i], model)
        if cached is not None:
            results[i] = cached
        else:
            misses.append(i)

    def _transcribe(i: int):
        try:
            raw = vision_client.describe_image(
                images[i], prompt=vision.PDF_LATEX_TRANSCRIBE_PROMPT
            )
            latex = vision.normalize_vision_latex(raw)
            latex = vision.sanitize_transient_vision_artifacts(latex)
            return i, (latex or None)
        except Exception as e:  # transient per-page failure → fall back, never abort
            print(f"  [Warn] vision page {i + 1} failed ({e}); using pymupdf4llm text.")
            return i, None

    if misses:
        # Parallelize only HTTP-based vision (Ollama). Agentic CLI clients
        # (claude/agy/codex) spawn subprocesses and are NOT safe to invoke
        # concurrently (rate limits / lock contention) → run them serially.
        concurrent_ok = getattr(vision_client, "supports_concurrent_calls", False)
        workers = max(1, min(vision.VISION_CONCURRENCY, len(misses))) if concurrent_ok else 1
        with ThreadPoolExecutor(max_workers=workers) as ex:
            for i, latex in ex.map(_transcribe, misses):
                results[i] = latex
        for i in misses:  # serial cache write
            latex = results.get(i)
            if latex:
                db.vision_cache_put(db_path, hashes[i], model, latex)

    new_texts: list[str] = []
    for i, page in enumerate(pdf_pages):
        parser_text = page.get("text", "") or ""
        page["parser_text"] = parser_text  # retain for audit / formula cross-check
        vlm_text = results.get(i)
        chosen = vlm_text if vlm_text else parser_text
        page["text"] = chosen
        if chosen.strip():
            new_texts.append(chosen)

    parsed.text = "\n\n".join(new_texts)
    parsed.metadata["parser_used"] = "vlm"


