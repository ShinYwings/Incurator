def add_file(
    paths: cfg.WikiPaths,
    source: Path,
) -> AddOutcome:
    """Add a single file to the tracking DB. Does not generate L1 summary.

    L1 summary generation requires an LLM client — call `generate_l1_summary()`
    separately after this returns `AddResult.ADDED`.
    """
    source = source.expanduser().resolve()

    # Guard: file must exist
    if not source.exists() or not source.is_file():
        return AddOutcome(
            result=AddResult.ERROR,
            source_path=source,
            relpath=str(source),
            message=f"File not found: {source}",
        )

    # Guard: file type must be supported
    if not parsers.is_supported(source):
        return AddOutcome(
            result=AddResult.SKIPPED_UNSUPPORTED,
            source_path=source,
            relpath=str(source),
            message=f"Unsupported file type: {source.suffix or '(no extension)'}",
        )

    # Guard: must be inside one of raw_dirs but NOT in collections
    in_raw = _is_inside_raw(source, paths.raw_dirs)
    try:
        source.relative_to(paths.collections.resolve())
        in_raw = False
    except ValueError:
        pass

    if not in_raw:
        return AddOutcome(
            result=AddResult.SKIPPED_UNSUPPORTED,
            source_path=source,
            relpath=str(source),
            message=(
                f"File is outside allowed raw directories or inside "
                f".curator/Collections: {source}"
            ),
        )

    # Parse
    try:
        resolved_source = _resolve_reference_source(paths, source)
        parsed = parsers.parse(resolved_source)
    except parsers.ParserError as e:
        return AddOutcome(
            result=AddResult.ERROR,
            source_path=source,
            relpath=str(source),
            message=f"Parse failed: {e}",
        )

    try:
        relpath = str(source.relative_to(paths.root.resolve()))
    except ValueError:
        relpath = str(source)

    with db.connect(paths.state_db) as conn:
        existing = conn.execute(
            "SELECT id, relpath, content_hash, context_id FROM sources WHERE relpath = ?",
            (relpath,),
        ).fetchone()

        if existing is not None:
            if existing["content_hash"] == parsed.content_hash:
                _record_pdf_pages_conn(conn, existing["id"], relpath, parsed)
                return AddOutcome(
                    result=AddResult.DEDUPED,
                    source_path=source,
                    relpath=relpath,
                    title=parsed.title,
                    file_type=parsed.file_type,
                    bytes=parsed.bytes,
                    word_count=parsed.word_count,
                    content_hash=parsed.content_hash,
                    source_id=existing["id"],
                    context_id=existing["context_id"],
                    message=f"Already tracked and unmodified: #{existing['id']}",
                )
            else:
                # Content changed — reset to pending, clear L1 Context ID
                conn.execute(
                    "UPDATE sources SET content_hash = ?, bytes = ?, status = 'pending', "
                    "last_ingested = NULL, context_id = NULL, "
                    "l1_status = 'pending', l2_status = 'pending', "
                    "l3_status = 'pending', l4_status = 'pending', layer_error = NULL "
                    "WHERE id = ?",
                    (parsed.content_hash, parsed.bytes, existing["id"]),
                )
                _record_pdf_pages_conn(conn, existing["id"], relpath, parsed)
                return AddOutcome(
                    result=AddResult.ADDED,
                    source_path=source,
                    relpath=relpath,
                    title=parsed.title,
                    file_type=parsed.file_type,
                    bytes=parsed.bytes,
                    word_count=parsed.word_count,
                    content_hash=parsed.content_hash,
                    source_id=existing["id"],
                    message=f"Updated #{existing['id']} (content changed)",
                )

        # Near-empty check (likely scanned PDF)
        if parsed.is_empty:
            status = "error"
            message = (
                f"Extracted only {parsed.word_count} words — likely a scanned "
                f"PDF or empty file. OCR not yet supported."
            )
            result_kind = AddResult.SKIPPED_EMPTY
        else:
            status = "pending"
            message = f"Added as #?: {parsed.title}"
            result_kind = AddResult.ADDED

        error_reason = "empty_file" if parsed.is_empty else None
        cur = conn.execute(
            """
            INSERT INTO sources (relpath, content_hash, file_type, bytes, added_at, status, error_reason)
            VALUES (?, ?, ?, ?, ?, ?, ?)
            """,
            (
                relpath,
                parsed.content_hash,
                parsed.file_type,
                parsed.bytes,
                _now_iso(),
                status,
                error_reason,
            ),
        )
        source_id = cur.lastrowid
        _record_pdf_pages_conn(conn, source_id, relpath, parsed)
        if parsed.is_empty:
            conn.execute(
                "UPDATE sources SET l1_status = 'error', layer_error = ? WHERE id = ?",
                (error_reason, source_id),
            )
        message = message.replace("#?", f"#{source_id}")

    return AddOutcome(
        result=result_kind,
        source_path=source,
        relpath=relpath,
        title=parsed.title,
        file_type=parsed.file_type,
        bytes=parsed.bytes,
        word_count=parsed.word_count,
        content_hash=parsed.content_hash,
        source_id=source_id,
        message=message,
    )


def import_source_file(
    paths: cfg.WikiPaths,
    source: Path,
    *,
    policy: str = "mirror_03_to_04",
    destination: str | Path | None = None,
    dry_run: bool = False,
    logical_source_id: str = "",
) -> AddOutcome:
    """Safely copy an arbitrary file into the vault, then register it.

    The default policy mirrors files from 03_Notes into 04_Resources and puts
    external files under 04_Resources/Imports. Files already in allowed raw
    directories are registered in place unless the mirror policy remaps them.
    """
    if policy in {"reference", "ref"}:
        source = source.expanduser().resolve()
        if not source.exists() or not source.is_file():
            return AddOutcome(
                result=AddResult.ERROR,
                source_path=source,
                relpath=str(source),
                message=f"File not found: {source}",
            )
        if not parsers.is_supported(source):
            return AddOutcome(
                result=AddResult.SKIPPED_UNSUPPORTED,
                source_path=source,
                relpath=str(source),
                message=f"Unsupported file type: {source.suffix or '(no extension)'}",
            )
        try:
            parsed = parsers.parse(source)
        except parsers.ParserError as exc:
            return AddOutcome(
                result=AddResult.ERROR,
                source_path=source,
                relpath=str(source),
                message=f"Parse failed: {exc}",
            )

        logical_id = logical_source_id or _default_logical_source_id(source)
        existing_relpath: str | None = None
        with db.connect(paths.state_db) as conn:
            existing = conn.execute(
                "SELECT relpath FROM sources WHERE logical_source_id = ? OR external_path = ?",
                (logical_id, str(source)),
            ).fetchone()
            if existing is not None:
                existing_relpath = str(existing["relpath"])

        if existing_relpath:
            stub_path = paths.root / existing_relpath
            relpath = existing_relpath
        else:
            try:
                stub_path = _reference_stub_destination(paths, source, destination)
            except Exception as exc:
                return AddOutcome(
                    result=AddResult.ERROR,
                    source_path=source,
                    relpath=str(source),
                    message=str(exc),
                )
            # Reuse an existing stub for the same external document instead of
            # writing a duplicate `<name>-2.md` when the DB row is missing but
            # the stub file still exists on disk (e.g. after a state rebuild).
            existing_stub = _find_existing_reference_stub(stub_path.parent, logical_id)
            if existing_stub is not None:
                stub_path = existing_stub
            else:
                stub_path = _unique_destination(stub_path)
            relpath = str(stub_path.relative_to(paths.root.resolve()))

        if dry_run:
            return AddOutcome(
                result=AddResult.DEDUPED,
                source_path=source,
                relpath=relpath,
                title=parsed.title,
                file_type=parsed.file_type,
                bytes=parsed.bytes,
                word_count=parsed.word_count,
                content_hash=parsed.content_hash,
                message=(
                    "Dry run: would register external reference "
                    f"{source} as {logical_id}"
                ),
            )

        _write_reference_stub(
            stub_path,
            source=source,
            title=parsed.title,
            logical_source_id=logical_id,
        )
        outcome = add_file(paths, stub_path)
        source_id = outcome.source_id
        if source_id is None:
            return AddOutcome(
                result=outcome.result,
                source_path=source,
                relpath=relpath,
                title=outcome.title,
                file_type=outcome.file_type,
                bytes=outcome.bytes,
                word_count=outcome.word_count,
                content_hash=outcome.content_hash,
                message=outcome.message,
            )

        result_kind = AddResult.ADDED
        status = "pending"
        error_reason = None
        message = f"Added external reference as #?: {parsed.title}"
        if parsed.is_empty:
            status = "error"
            error_reason = "empty_file"
            result_kind = AddResult.SKIPPED_EMPTY
            message = (
                f"Extracted only {parsed.word_count} words — likely a scanned "
                f"PDF or empty file. OCR not yet supported."
            )

        with db.connect(paths.state_db) as conn:
            existing = conn.execute(
                "SELECT id, relpath, content_hash, context_id FROM sources WHERE id = ?",
                (source_id,),
            ).fetchone()
            if existing is not None:
                if existing["content_hash"] == parsed.content_hash:
                    conn.execute(
                        """
                        UPDATE sources
                        SET external_path = ?, is_reference = 1,
                            logical_source_id = ?, import_origin = ?,
                            import_policy = ?
                        WHERE id = ?
                        """,
                        (str(source), logical_id, str(source), "reference", existing["id"]),
                    )
                    _record_pdf_pages_conn(conn, existing["id"], relpath, parsed)
                    return AddOutcome(
                        result=AddResult.DEDUPED if outcome.result == AddResult.DEDUPED else result_kind,
                        source_path=source,
                        relpath=relpath,
                        title=parsed.title,
                        file_type=parsed.file_type,
                        bytes=parsed.bytes,
                        word_count=parsed.word_count,
                        content_hash=parsed.content_hash,
                        source_id=existing["id"],
                        context_id=existing["context_id"],
                        message=(
                            f"Already tracked external reference: #{existing['id']}"
                            if outcome.result == AddResult.DEDUPED
                            else f"Added external reference as #{existing['id']}: {parsed.title}"
                        ),
                    )
                conn.execute(
                    """
                    UPDATE sources
                    SET relpath = ?, content_hash = ?, file_type = ?, bytes = ?,
                        status = ?, last_ingested = NULL, context_id = NULL,
                        l1_status = 'pending', l2_status = 'pending',
                        l3_status = 'pending', l4_status = 'pending',
                        layer_error = NULL, error_reason = ?,
                        external_path = ?, is_reference = 1,
                        logical_source_id = ?, import_origin = ?,
                        import_policy = ?
                    WHERE id = ?
                    """,
                    (
                        relpath,
                        parsed.content_hash,
                        parsed.file_type,
                        parsed.bytes,
                        status,
                        error_reason,
                        str(source),
                        logical_id,
                        str(source),
                        "reference",
                        existing["id"],
                    ),
                )
                source_id = int(existing["id"])
                result_kind = AddResult.ADDED
                message = f"Updated external reference #{source_id} (content changed)"
            else:
                cur = conn.execute(
                    """
                    INSERT INTO sources
                        (relpath, content_hash, file_type, bytes, added_at,
                         status, error_reason, external_path, is_reference,
                         logical_source_id, import_origin, import_policy)
                    VALUES (?, ?, ?, ?, ?, ?, ?, ?, 1, ?, ?, ?)
                    """,
                    (
                        relpath,
                        parsed.content_hash,
                        parsed.file_type,
                        parsed.bytes,
                        _now_iso(),
                        status,
                        error_reason,
                        str(source),
                        logical_id,
                        str(source),
                        "reference",
                    ),
                )
                if cur.lastrowid is None:
                    raise RuntimeError("failed to create source row")
                source_id = int(cur.lastrowid)

            _record_pdf_pages_conn(conn, source_id, relpath, parsed)
            if parsed.is_empty:
                conn.execute(
                    "UPDATE sources SET l1_status = 'error', layer_error = ? WHERE id = ?",
                    (error_reason, source_id),
                )
            message = message.replace("#?", f"#{source_id}")

        return AddOutcome(
            result=result_kind,
            source_path=source,
            relpath=relpath,
            title=parsed.title,
            file_type=parsed.file_type,
            bytes=parsed.bytes,
            word_count=parsed.word_count,
            content_hash=parsed.content_hash,
            source_id=source_id,
            message=message,
        )

    try:
        plan = safe_import_destination(
            paths,
            source,
            policy=policy,
            destination=destination,
        )
    except Exception as exc:
        return AddOutcome(
            result=AddResult.ERROR,
            source_path=source,
            relpath=str(source),
            message=str(exc),
        )

    if dry_run:
        return AddOutcome(
            result=AddResult.DEDUPED,
            source_path=plan.source_path,
            relpath=plan.relpath,
            message=(
                "Dry run: would "
                + ("copy" if plan.copied else "register")
                + f" {plan.source_path} -> {plan.destination_path}"
            ),
        )

    if plan.copied:
        plan.destination_path.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(plan.source_path, plan.destination_path)

    outcome = add_file(paths, plan.destination_path)
    if outcome.source_id is not None:
        with db.connect(paths.state_db) as conn:
            conn.execute(
                """
                UPDATE sources
                SET import_origin = ?, import_policy = ?, is_reference = 0
                WHERE id = ?
                """,
                (str(plan.source_path), plan.policy, outcome.source_id),
            )

    if plan.copied and outcome.result != AddResult.ERROR:
        outcome.message = f"{outcome.message} (imported from {plan.source_path})"
    return outcome


def iter_addable_files(root: Path, recursive: bool) -> Iterable[Path]:
    """Yield every supported file at or under `root`."""
    root = root.expanduser().resolve()
    if not root.exists():
        return
    if root.is_file():
        if parsers.is_supported(root):
            yield root
        return
    if root.is_dir():
        iterator = root.rglob("*") if recursive else root.iterdir()
        for child in iterator:
            if child.is_file() and not child.name.startswith(".") and parsers.is_supported(child):
                yield child


