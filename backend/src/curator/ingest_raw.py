class AddResult(str, Enum):
    ADDED = "added"
    DEDUPED = "deduped"
    SKIPPED_EMPTY = "skipped_empty"
    SKIPPED_UNSUPPORTED = "skipped_unsupported"
    ERROR = "error"


@dataclass
class AddOutcome:
    """Result of attempting to add a single file."""

    result: AddResult
    source_path: Path              # Where the file ended up (or original on error)
    relpath: str                   # Relative to project root
    title: str | None = None
    file_type: str | None = None
    bytes: int = 0
    word_count: int = 0
    content_hash: str | None = None
    source_id: int | None = None   # Row ID in sources table
    context_id: str | None = None  # CTX-UUID for L1 context page
    message: str = ""              # Human-friendly explanation

    @property
    def ok(self) -> bool:
        return self.result == AddResult.ADDED

    @property
    def is_warning(self) -> bool:
        return self.result in {
            AddResult.DEDUPED,
            AddResult.SKIPPED_EMPTY,
            AddResult.SKIPPED_UNSUPPORTED,
        }


@dataclass
class ImportPlan:
    """Resolved destination for a source import."""

    source_path: Path
    destination_path: Path
    relpath: str
    policy: str
    copied: bool


def _default_logical_source_id(source: Path) -> str:
    """Create a deterministic logical id from the source path.

    This is a v1 fallback. Dedicated integrations such as Zotero should replace
    it with the external system's stable item key when available.
    """
    digest = hashlib.sha256(str(source.expanduser().resolve()).encode("utf-8")).hexdigest()
    return f"ref-{digest[:16]}"


import os

def _resolve_reference_source(paths: cfg.WikiPaths, source: Path) -> Path:
    """Resolve Reference Mode Markdown Stubs to their actual external target.
    
    If the file is a markdown stub with `type: reference` frontmatter, returns the
    resolved absolute path of the external file (e.g. from Zotero). Otherwise returns
    the original source unmodified.
    """
    if source.suffix.lower() != ".md":
        return source
    
    try:
        content = source.read_text(encoding="utf-8")
        if not content.startswith("---"):
            return source
            
        end_idx = content.find("---", 3)
        if end_idx == -1:
            return source
            
        import yaml
        fm = yaml.safe_load(content[3:end_idx])
        if not isinstance(fm, dict) or fm.get("type") != "reference":
            return source
            
        target_path = None
        if fm.get("zotero_key"):
            from . import zotero
            # Check config or env for zotero roots
            zotero_roots = []
            config = cfg.load_config(paths)
            if "external" in config and "zotero" in config["external"]:
                zotero_roots = config["external"]["zotero"].get("roots", [])
            
            env_zotero = os.environ.get("ZOTERO_BASE_PATH")
            if env_zotero:
                zotero_roots.insert(0, env_zotero)
                
            for z_root in zotero_roots:
                resolved = zotero.resolve_zotero_attachment_path(z_root, fm["zotero_key"])
                if resolved:
                    target_path = resolved
                    break
        
        if not target_path and fm.get("target_path"):
            target_path = fm["target_path"]
            
        if target_path:
            target_p = Path(target_path)
            if target_p.exists():
                return target_p
    except Exception:
        pass
        
    return source


