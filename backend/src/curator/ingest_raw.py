def _now_iso() -> str:
    return datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")


def _today_iso() -> str:
    return datetime.now(timezone.utc).strftime("%Y-%m-%d")


def _generate_id(prefix: str) -> str:
    """Generate a prefixed UUID4, e.g. 'CTX-a1b2c3d4'."""
    return f"{prefix}-{uuid.uuid4().hex[:8]}"


def _is_inside_raw(path: Path, raw_dirs: list[Path]) -> bool:
    """True if `path` is already inside one of the project's raw directories."""
    path = path.resolve()
    for d in raw_dirs:
        try:
            path.relative_to(d.resolve())
            return True
        except ValueError:
            pass
    return False


def _is_inside(path: Path, parent: Path) -> bool:
    try:
        path.resolve().relative_to(parent.resolve())
        return True
    except ValueError:
        return False


def _safe_relative_path(path: Path) -> Path:
    if path.is_absolute():
        raise ValueError("Destination must be vault-relative, not absolute.")
    parts = []
    for part in path.parts:
        if part in ("", "."):
            continue
        if part == "..":
            raise ValueError("Destination may not contain '..'.")
        parts.append(part)
    if not parts:
        raise ValueError("Destination path is empty.")
    return Path(*parts)


def _unique_destination(path: Path) -> Path:
    if not path.exists():
        return path
    stem = path.stem
    suffix = path.suffix
    parent = path.parent
    for idx in range(2, 10_000):
        candidate = parent / f"{stem}-{idx}{suffix}"
        if not candidate.exists():
            return candidate
    raise FileExistsError(f"Could not find a free destination near {path}")


def _reference_stub_destination(paths: cfg.WikiPaths, source: Path, destination: str | Path | None = None) -> Path:
    resources_dir = paths.root.resolve() / consts.DIR_RESOURCES
    if destination is None:
        dest = resources_dir / "References" / f"{source.stem}.md"
    else:
        rel_dest = _safe_relative_path(Path(destination))
        dest = paths.root.resolve() / rel_dest
        if dest.suffix == "":
            dest = dest / f"{source.stem}.md"
    dest = dest.resolve()
    if not _is_inside(dest, resources_dir):
        raise ValueError("Reference stub destination must stay inside 04_Resources.")
    return dest


def _find_existing_reference_stub(directory: Path, logical_id: str) -> Path | None:
    """Return an existing reference stub in ``directory`` for ``logical_id``.

    Reference Mode keys an external document by its stable ``logical_source_id``
    (e.g. ``zotero:<attachmentKey>``). If a stub for that id already exists on
    disk we must reuse it instead of writing a duplicate ``<name>-2.md``. This
    happens when the stub file survives but its ``sources`` DB row does not —
    for example after a ``state.sqlite`` rebuild or a testbed re-init — so the
    DB dedup lookup misses and the destination would otherwise collide.
    """
    if not logical_id or not directory.is_dir():
        return None
    import yaml

    for candidate in sorted(directory.glob("*.md")):
        try:
            content = candidate.read_text(encoding="utf-8")
            if not content.startswith("---"):
                continue
            end_idx = content.find("---", 3)
            if end_idx == -1:
                continue
            fm = yaml.safe_load(content[3:end_idx])
        except Exception:
            continue
        if (
            isinstance(fm, dict)
            and fm.get("type") == "reference"
            and fm.get("logical_source_id") == logical_id
        ):
            return candidate.resolve()
    return None


def _write_reference_stub(
    stub_path: Path,
    *,
    source: Path,
    title: str,
    logical_source_id: str,
) -> None:
    import yaml

    zotero_attachment_key = ""
    if logical_source_id.startswith("zotero:"):
        zotero_attachment_key = logical_source_id.split(":", 1)[1]

    frontmatter = {
        "type": "reference",
        "title": title,
        "logical_source_id": logical_source_id,
    }
    if zotero_attachment_key:
        frontmatter["reference_kind"] = "zotero"
        frontmatter["zotero_attachment_key"] = zotero_attachment_key
    stub_path.parent.mkdir(parents=True, exist_ok=True)
    fm = yaml.safe_dump(frontmatter, sort_keys=False, allow_unicode=True).strip()
    body = (
        f"# {title}\n\n"
        "External source reference. The backend resolves the local file path "
        "from device-local source metadata or an external library integration.\n"
    )
    if zotero_attachment_key:
        body += (
            f"\nObsidian PDF viewer: zotero://open-pdf/library/items/{zotero_attachment_key}?viewer=obsidian\n"
            f"Zotero PDF: zotero://open-pdf/library/items/{zotero_attachment_key}\n"
        )
    stub_path.write_text(
        f"---\n{fm}\n---\n\n{body}",
        encoding="utf-8",
    )


def safe_import_destination(
    paths: cfg.WikiPaths,
    source: Path,
    *,
    policy: str = "mirror_03_to_04",
    destination: str | Path | None = None,
) -> ImportPlan:
    """Resolve a safe destination for importing a source into the vault.

    `mirror_03_to_04` keeps direct imports out of human-authored 03_Notes by
    mirroring those paths under 04_Resources. Other external files land under
    04_Resources/Imports. Files already inside an allowed raw directory are
    reused in place unless the mirror policy maps 03_Notes to 04_Resources.
    """
    if policy == "copy":
        policy = "into_04_resources"
    if policy not in {"mirror_03_to_04", "into_04_resources"}:
        raise ValueError(f"Unsupported import policy: {policy}")

    source = source.expanduser().resolve()
    if not source.exists() or not source.is_file():
        raise FileNotFoundError(f"File not found: {source}")
    if not parsers.is_supported(source):
        raise ValueError(f"Unsupported file type: {source.suffix or '(no extension)'}")

    root = paths.root.resolve()
    resources_dir = root / consts.DIR_RESOURCES
    notes_dir = root / consts.DIR_NOTES
    collections_dir = paths.collections.resolve()

    if _is_inside(source, collections_dir):
        raise ValueError("Refusing to import from .curator/Collections.")

    if destination is not None:
        rel_dest = _safe_relative_path(Path(destination))
        dest = root / rel_dest
        if dest.suffix == "":
            dest = dest / source.name
    elif policy == "mirror_03_to_04" and _is_inside(source, notes_dir):
        dest = resources_dir / source.relative_to(notes_dir)
    elif _is_inside_raw(source, paths.raw_dirs):
        return ImportPlan(
            source_path=source,
            destination_path=source,
            relpath=str(source.relative_to(root)) if _is_inside(source, root) else str(source),
            policy=policy,
            copied=False,
        )
    else:
        dest = resources_dir / "Imports" / source.name

    dest = dest.resolve()
    if not _is_inside(dest, resources_dir):
        raise ValueError("Import destination must stay inside 04_Resources.")
    if _is_inside(dest, collections_dir):
        raise ValueError("Import destination may not be inside .curator/Collections.")

    try:
        if source.samefile(dest):
            return ImportPlan(
                source_path=source,
                destination_path=source,
                relpath=str(source.relative_to(root)) if _is_inside(source, root) else str(source),
                policy=policy,
                copied=False,
            )
    except OSError:
        pass

    dest = _unique_destination(dest)
    return ImportPlan(
        source_path=source,
        destination_path=dest,
        relpath=str(dest.relative_to(root)),
        policy=policy,
        copied=True,
    )


