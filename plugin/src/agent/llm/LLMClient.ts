const AGY_READ_PERMISSION = "$read_file$()";
const INCURATOR_AGY_POLICY_HEADER =
  "# Auto-generated by Incurator plugin — do not edit manually.";

/**
 * Prepare Antigravity CLI for non-interactive PDF/image reads without granting
 * blanket tool approval. Antigravity 1.1.3+ soft-denies unapproved tools in
 * headless mode and 1.1.5+ reads persisted permissions from this CLI-specific
 * settings file.
 */
export function syncAgyHeadlessReadPermission(geminiDir: string): void {
  const cliDir = join(geminiDir, "antigravity-cli");
  const settingsPath = join(cliDir, "settings.json");
  mkdirSync(cliDir, { recursive: true });

  let existing: Record<string, unknown> = {};
  if (existsSync(settingsPath)) {
    let parsed: unknown;
    try {
      parsed = JSON.parse(readFileSync(settingsPath, "utf-8"));
    } catch (error) {
      throw new Error(
        `Antigravity CLI settings are malformed; refusing to overwrite ${settingsPath}: ${error instanceof Error ? error.message : String(error)}`,
      );
    }
    if (!parsed || typeof parsed !== "object" || Array.isArray(parsed)) {
      throw new Error(
        `Antigravity CLI settings must be a JSON object; refusing to overwrite ${settingsPath}.`,
      );
    }
    existing = parsed as Record<string, unknown>;
  }

  const rawPermissions = existing.permissions;
  if (
    rawPermissions !== undefined &&
    (!rawPermissions || typeof rawPermissions !== "object" || Array.isArray(rawPermissions))
  ) {
    throw new Error(
      `Antigravity CLI settings permissions must be an object; refusing to overwrite ${settingsPath}.`,
    );
  }
  const permissions = (rawPermissions ?? {}) as Record<string, unknown>;
  const rawAllow = permissions.allow;
  if (
    rawAllow !== undefined &&
    (!Array.isArray(rawAllow) || rawAllow.some((entry) => typeof entry !== "string"))
  ) {
    throw new Error(
      `Antigravity CLI settings permissions.allow must be a string array; refusing to overwrite ${settingsPath}.`,
    );
  }
  const allow = (rawAllow as string[] | undefined) ?? [];
  const merged = {
    ...existing,
    permissions: {
      ...permissions,
      allow: allow.includes(AGY_READ_PERMISSION)
        ? allow
        : [...allow, AGY_READ_PERMISSION],
    },
  };

  const tempPath = join(
    cliDir,
    `settings.json.incurator-${process.pid}-${Math.random().toString(36).slice(2)}.tmp`,
  );
  try {
    writeFileSync(tempPath, `${JSON.stringify(merged, null, 2)}\n`);
    renameSync(tempPath, settingsPath);
  } finally {
    rmSync(tempPath, { force: true });
  }

  const obsoletePolicyPath = join(geminiDir, "policies", "incurator-read.toml");
  try {
    if (
      existsSync(obsoletePolicyPath) &&
      readFileSync(obsoletePolicyPath, "utf-8").startsWith(INCURATOR_AGY_POLICY_HEADER)
    ) {
      unlinkSync(obsoletePolicyPath);
    }
  } catch (error) {
    logger.warn(
      `Could not clean obsolete Incurator Antigravity policy ${obsoletePolicyPath}: ${error instanceof Error ? error.message : String(error)}`,
    );
  }
}
