// ─── Provider-specific request builders ─────────────────────────

interface ProviderAdapter {
  buildUrl(model: string): string;
  buildHeaders(credential: CLICredential): Record<string, string>;
  buildBody(
    messages: LLMMessage[],
    stream: boolean,
    tools?: any[]
  ): Record<string, unknown>;
  parseStreamChunk(raw: string): StreamChunk | null;
  parseFullResponse(json: unknown): string;
}

// ─── Base Adapter (shared SSE envelope + default headers) ────────

/**
 * Common behaviour shared by all provider adapters:
 *  - default Bearer + Content-Type headers (Claude adds anthropic-version)
 *  - SSE envelope parsing (`data: ` prefix, `[DONE]`, JSON.parse + try/catch)
 *
 * Subclasses implement the genuinely provider-specific bits: buildUrl,
 * buildBody, parseFullResponse, and extractDelta (pulling text/done out of a
 * parsed SSE data object).
 */
abstract class BaseProviderAdapter implements ProviderAdapter {
  abstract buildUrl(model: string): string;
  abstract buildBody(
    messages: LLMMessage[],
    stream: boolean,
    tools?: any[]
  ): Record<string, unknown>;
  abstract parseFullResponse(json: unknown): string;

  buildHeaders(credential: CLICredential): Record<string, string> {
    return {
      Authorization: `Bearer ${credential.token}`,
      "Content-Type": "application/json",
    };
  }

  parseStreamChunk(raw: string): StreamChunk | null {
    const line = raw.trim();
    if (!line.startsWith("data: ")) return null;
    const json = line.slice(6);
    if (json === "[DONE]") return { text: "", done: true };
    let parsed: any;
    try {
      parsed = JSON.parse(json);
    } catch {
      return null;
    }
    return this.extractDelta(parsed);
  }

  /** Extract {text, done} from one parsed SSE data object (provider-specific). */
  protected abstract extractDelta(parsed: any): StreamChunk | null;
}

// ─── Antigravity Adapter ────────────────────────────────────────

class AntigravityAdapter extends BaseProviderAdapter {
  buildUrl(model: string): string {
    return `https://generativelanguage.googleapis.com/v1beta/models/${model}:streamGenerateContent?alt=sse`;
  }

  buildBody(messages: LLMMessage[]): Record<string, unknown> {
    const contents = messages
      .filter((m) => m.role !== "system")
      .map((m) => ({
        role: m.role === "assistant" ? "model" : "user",
        parts: this.toParts(m.content),
      }));

    const systemMsg = messages.find((m) => m.role === "system");
    const body: Record<string, unknown> = { contents };
    if (systemMsg) {
      body.systemInstruction = {
        parts: [
          {
            text:
              typeof systemMsg.content === "string"
                ? systemMsg.content
                : systemMsg.content
                    .filter((p) => p.type === "text")
                    .map((p) => (p as { type: "text"; text: string }).text)
                    .join("\n"),
          },
        ],
      };
    }
    return body;
  }

  private toParts(
    content: string | LLMContentPart[]
  ): Array<Record<string, unknown>> {
    if (typeof content === "string") {
      return [{ text: content }];
    }
    return content.map((part) => {
      if (part.type === "text") return { text: part.text };
      return {
        inlineData: { mimeType: part.mimeType, data: part.data },
      };
    });
  }

  protected extractDelta(parsed: any): StreamChunk | null {
    const text = parsed?.candidates?.[0]?.content?.parts?.[0]?.text || "";
    const reason = parsed?.candidates?.[0]?.finishReason as string | undefined;
    // Gemini ends a complete answer with "STOP"; an output-cap cut-off is
    // "MAX_TOKENS" (a recoverable truncation → auto-continue). SAFETY/RECITATION
    // are content-filter blocks that terminate the stream but must NOT be
    // continued. Any non-empty finishReason terminates the stream.
    if (reason === "MAX_TOKENS") {
      return { text, done: true, finishReason: "length", truncated: true };
    }
    if (reason === "SAFETY" || reason === "RECITATION") {
      return { text, done: true, finishReason: "content_filter" };
    }
    return reason ? { text, done: true, finishReason: "stop" } : { text, done: false };
  }

  parseFullResponse(json: unknown): string {
    const data = json as {
      candidates?: Array<{
        content?: { parts?: Array<{ text?: string }> };
      }>;
    };
    return data?.candidates?.[0]?.content?.parts?.[0]?.text || "";
  }
}

// ─── Claude Adapter ─────────────────────────────────────────────

class ClaudeAdapter extends BaseProviderAdapter {
  buildUrl(): string {
    return "https://api.anthropic.com/v1/messages";
  }

  buildHeaders(credential: CLICredential): Record<string, string> {
    return {
      Authorization: `Bearer ${credential.token}`,
      "anthropic-version": "2023-06-01",
      "Content-Type": "application/json",
    };
  }

  buildBody(
    messages: LLMMessage[],
    stream: boolean,
    tools?: any[]
  ): Record<string, unknown> {
    const systemMsg = messages.find((m) => m.role === "system");
    const chatMessages = messages
      .filter((m) => m.role !== "system")
      .map((m) => ({
        role: m.role,
        content: this.toContent(m.content),
      }));

    return {
      model: "", // Will be overridden
      max_tokens: 8192,
      stream,
      ...(systemMsg
        ? {
            system:
              typeof systemMsg.content === "string"
                ? systemMsg.content
                : systemMsg.content
                    .filter((p) => p.type === "text")
                    .map(
                      (p) => (p as { type: "text"; text: string }).text
                    )
                    .join("\n"),
          }
        : {}),
      messages: chatMessages,
    };
  }

  private toContent(
    content: string | LLMContentPart[]
  ): string | Array<Record<string, unknown>> {
    if (typeof content === "string") return content;
    return content.map((part) => {
      if (part.type === "text") return { type: "text", text: part.text };
      return {
        type: "image",
        source: {
          type: "base64",
          media_type: part.mimeType,
          data: part.data,
        },
      };
    });
  }

  protected extractDelta(parsed: any): StreamChunk | null {
    if (parsed.type === "content_block_delta") {
      return { text: parsed.delta?.text || "", done: false };
    }
    // Claude reports the terminal reason on `message_delta` (stop_reason:
    // "end_turn" | "max_tokens" | "tool_use" | ...) just before `message_stop`.
    // Surface a truncation flag here so the chat layer can auto-continue.
    if (parsed.type === "message_delta" && parsed.delta?.stop_reason === "max_tokens") {
      return { text: "", done: false, finishReason: "length", truncated: true };
    }
    if (parsed.type === "message_stop") {
      return { text: "", done: true };
    }
    return null;
  }

  parseFullResponse(json: unknown): string {
    const data = json as {
      content?: Array<{ type: string; text?: string }>;
    };
    return (
      data?.content
        ?.filter((b) => b.type === "text")
        .map((b) => b.text || "")
        .join("") || ""
    );
  }
}

